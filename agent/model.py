"""Minimal Groq chat-completions client using the OpenAI-compatible endpoint."""
from __future__ import annotations

import json
import os
import time
import urllib.error
import urllib.request


class ModelError(RuntimeError):
    """Purpose: Represent a safe-to-display model error.

    Input: A short error message without credentials.
    Output: An exception that the CLI can catch and report.
    What it does: Separates model/API problems from regular program flow.
    """


class RateLimitError(ModelError):
    """Purpose: Identify an API rate-limit response.

    Input: A rate-limit explanation from the model client.
    Output: A ModelError subtype understood by the command-line program.
    What it does: Lets the program stop safely and resume later.
    """

    pass


class GroqClient:
    """Purpose: Send chat requests to Groq's OpenAI-compatible API.

    Input: GROQ_API_KEY and optionally GROQ_MODEL from environment variables.
    Output: Text generated by the configured Groq model.
    What it does: Handles request formatting and a small bounded retry policy.
    """

    def __init__(self) -> None:
        """Purpose: Read and validate the Groq connection settings.

        Input: No arguments; reads environment variables.
        Output: An initialized client, or ModelError if the key is missing.
        What it does: Keeps credentials outside source code and saved files.
        """
        self.api_key = os.getenv("GROQ_API_KEY", "").strip()
        self.model = os.getenv("GROQ_MODEL", "llama-3.3-70b-versatile").strip()
        if not self.api_key or self.api_key == "replace_me":
            raise ModelError("GROQ_API_KEY is missing. Add it to the environment or agent/.env.")

    def complete(self, system: str, user: str, *, json_mode: bool = False) -> str:
        """Purpose: Ask Groq to complete one chat request.

        Input: system/user instructions and optional JSON response mode.
        Output: The model's response text.
        What it does: Posts to Groq, retries temporary failures at most twice,
        and raises a safe ModelError when the request cannot be completed.
        """
        body: dict = {
            "model": self.model,
            "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
            "temperature": 0.2,
        }
        if json_mode:
            body["response_format"] = {"type": "json_object"}
        request = urllib.request.Request(
            "https://api.groq.com/openai/v1/chat/completions",
            data=json.dumps(body).encode("utf-8"),
            headers={"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"},
            method="POST",
        )
        # Bounded backoff for transient gateway errors; rate limits stop immediately so state is safe.
        for attempt in range(3):
            try:
                with urllib.request.urlopen(request, timeout=90) as response:
                    payload = json.loads(response.read().decode("utf-8"))
                return payload["choices"][0]["message"]["content"]
            except urllib.error.HTTPError as exc:
                detail = exc.read().decode("utf-8", errors="replace")[:1000]
                if exc.code == 429:
                    raise RateLimitError(f"Groq rate limit (HTTP 429). Progress is saved. Details: {detail}") from None
                if exc.code >= 500 and attempt < 2:
                    time.sleep(1.5 * (attempt + 1))
                    continue
                raise ModelError(f"Groq request failed (HTTP {exc.code}): {detail}") from None
            except (urllib.error.URLError, TimeoutError, json.JSONDecodeError, KeyError, IndexError) as exc:
                if attempt < 2 and isinstance(exc, (urllib.error.URLError, TimeoutError)):
                    time.sleep(1.5 * (attempt + 1))
                    continue
                raise ModelError(f"Groq request failed: {type(exc).__name__}: {exc}") from None
        raise ModelError("Groq request failed after bounded retries.")
